import { readFileSync, writeFileSync } from "node:fs";

const t = JSON.parse(readFileSync(new URL("./tokens.json", import.meta.url), "utf8"));
const kebab = (s) => s.replace(/[A-Z]/g, (c) => "-" + c.toLowerCase());
const pascal = (s) => s[0].toUpperCase() + s.slice(1);
const write = (path, body) => writeFileSync(new URL(path, import.meta.url), body);

const colors = (theme) => Object.entries(t.color[theme]).map(([k, v]) => `  --vox-${kebab(k)}: ${v};`);
const brands = Object.entries(t.brand).map(([k, v]) => `  --vox-brand-${kebab(k)}: ${v};`);
const radii = Object.entries(t.radius).map(([k, v]) => `  --vox-radius-${k}: ${v}px;`);

const css = `/* Generated by vox-shared/theme/build.mjs from tokens.json. Do not edit. */
:root,
[data-theme="dark"] {
${colors("dark").join("\n")}
${brands.join("\n")}
${radii.join("\n")}
  color-scheme: dark;
}

[data-theme="light"] {
${colors("light").join("\n")}
  color-scheme: light;
}
`;
write("./dist/vox-theme.css", css);
write("../../vox-web/src/app/theme.css", css);
write("../../vox-desktop/src/styles/vox-theme.css", css);
write(
  "../../vox-desktop/src/styles/vox-tokens.ts",
  `// Generated by vox-shared/theme/build.mjs from tokens.json. Do not edit.
export const VOX_COLORS = ${JSON.stringify(Object.keys(t.color.dark).map(kebab))} as const;
export type VoxColor = (typeof VOX_COLORS)[number];
export const VOX_BRANDS = ${JSON.stringify(Object.keys(t.brand).map(kebab))} as const;
export type VoxBrand = (typeof VOX_BRANDS)[number];
`,
);

write(
  "../../vox-web/src/lib/vox-tokens.ts",
  `// Generated by vox-shared/theme/build.mjs from tokens.json. Do not edit.
export const VOX_THEME = ${JSON.stringify(t.color, null, 2)} as const;
export type VoxColor = ${Object.keys(t.color.dark).map((k) => JSON.stringify(kebab(k))).join(" | ")};
`,
);

const kotlinColors = (name, theme) => [
  `object ${name} {`,
  ...Object.entries(t.color[theme]).map(([k, v]) => `    val ${pascal(k)} = Color(0xFF${v.slice(1).toUpperCase()})`),
  "}",
  "",
];
write(
  "./dist/VoxTheme.kt",
  [
    "package com.vox.theme",
    "",
    "import androidx.compose.ui.graphics.Color",
    "import androidx.compose.ui.unit.dp",
    "",
    ...kotlinColors("VoxColors", "dark"),
    ...kotlinColors("VoxLightColors", "light"),
    "object VoxBrandColors {",
    ...Object.entries(t.brand).map(([k, v]) => `    val ${pascal(k)} = Color(0xFF${v.slice(1).toUpperCase()})`),
    "}",
    "",
    "object VoxRadius {",
    ...Object.entries(t.radius).map(([k, v]) => `    val ${pascal(k)} = ${v}.dp`),
    "}",
    "",
  ].join("\n"),
);
